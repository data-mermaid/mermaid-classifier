"""Select source-grouped test groups and cross-validation folds for a config.

Reads the config's annotations (read, rollup, filter, dedupe; no feature
listing or download), then writes ``holdout_groups.csv`` (columns
``site, group_id, fold``) and a per-class coverage report beside it. A group
is a CoralNet source or a MERMAID project. CoralNet test candidates exclude
every source listed in ``--beta-sources``; MERMAID groups need the config's
``mermaid_project_lookup_uri``, otherwise MERMAID holdout is skipped. Unless
``--no-write-fold-configs`` is given, it also writes one config dir per CV fold,
``<config-dir>_fold{k}/``, for the launcher.

Usage (from the repo root)::

    uv run python scripts/select_holdout_groups.py \\
        --config-dir sagemaker/configs/coralnet_all_plus_mermaid_coarse_grouped
"""

from __future__ import annotations

import argparse
import copy
import csv
import dataclasses
import shutil
from pathlib import Path

import pandas as pd
import yaml
from classifier_train import (
    _resolve_local_aws_credentials,  # pyright: ignore[reportPrivateUsage]  # shared local-credential bootstrap
)

REPO_ROOT = Path(__file__).resolve().parent.parent
WORKSPACE_ROOT = REPO_ROOT.parent
DEFAULT_BETA_SOURCES = WORKSPACE_ROOT / "sagemaker" / "sources" / "OldCoralNetSourcesToKeep.csv"
CONFIG_FILENAME = "training_config.yaml"
COVERAGE_SUFFIX = "_coverage.csv"
MERMAID_SITE = "mermaid"


def read_beta_sources(path: Path) -> set[str]:
    """The `id` column of the Beta source list, as strings; raises if it is absent or empty."""
    with path.open(newline="") as f:
        reader = csv.DictReader(f)
        if "id" not in (reader.fieldnames or []):
            raise ValueError(f"{path} has no 'id' column (columns: {reader.fieldnames}).")
        ids = {row["id"].strip() for row in reader if (row["id"] or "").strip()}
    if not ids:
        raise ValueError(f"{path} lists no ids, so no CoralNet source would be barred from test.")
    return ids


def write_holdout_csv(path: Path, assignments: dict[tuple[str, str], str]) -> None:
    with path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["site", "group_id", "fold"])
        for (site, group_id), fold in sorted(assignments.items()):
            writer.writerow([site, group_id, fold])


def write_fold_configs(config_dir: Path, groups_csv: Path, folds: int) -> list[Path]:
    """
    Write `<config_dir>_fold{k}/` siblings for k in 0..folds-1; return them.

    Each fold config is the parent YAML with `holdout_fold` set to k,
    `mlflow.experiment_name` suffixed `-cv` and `mlflow.model_name` suffixed
    `-cv-fold{k}`. The launcher uploads a config dir as a unit, so `../` paths
    would not exist remotely: each fold dir gets its own copy of the label
    CSVs the parent references and of `groups_csv`.
    """
    from mermaid_classifier.sagemaker.config import TrainingRunConfig

    raw = yaml.safe_load((config_dir / CONFIG_FILENAME).read_text())
    config = TrainingRunConfig.model_validate(raw)
    mlflow_block = raw["mlflow"]
    dataset = config.dataset
    if not mlflow_block.get("experiment_name") or not mlflow_block.get("model_name"):
        raise ValueError(
            "The parent config needs mlflow.experiment_name and mlflow.model_name,"
            " so fold runs never register under the parent's names."
        )
    if dataset.holdout_groups_csv is None:
        raise ValueError("The parent config sets no dataset.holdout_groups_csv.")
    sources = {
        name: config_dir / name
        for name in (
            dataset.label_rollup_spec_csv,
            dataset.included_labels_csv,
            dataset.excluded_labels_csv,
            dataset.excluded_images_csv,
        )
        if name
    }
    sources[dataset.holdout_groups_csv] = groups_csv

    written: list[Path] = []
    for k in range(folds):
        fold_dir = config_dir.with_name(f"{config_dir.name}_fold{k}")
        fold_dir.mkdir(exist_ok=True)
        fold_raw = copy.deepcopy(raw)
        fold_raw["dataset"]["holdout_fold"] = k
        fold_raw["mlflow"]["experiment_name"] = f"{mlflow_block['experiment_name']}-cv"
        fold_raw["mlflow"]["model_name"] = f"{mlflow_block['model_name']}-cv-fold{k}"
        header = (
            f"# Generated by scripts/select_holdout_groups.py from {config_dir.name}:"
            f" CV fold {k}.\n# Edit the parent and regenerate instead of editing this file.\n"
        )
        (fold_dir / CONFIG_FILENAME).write_text(header + yaml.safe_dump(fold_raw, sort_keys=False))
        for name, src in sources.items():
            shutil.copyfile(src, fold_dir / name)
        written.append(fold_dir)
    return written


def _resolve(path: str, base: Path) -> Path:
    p = Path(path)
    return (p if p.is_absolute() else base / p).resolve()


def resolve_out_path(
    out: str | None, config_dir: Path, parent_csv: Path | None, write_fold_configs: bool
) -> Path:
    """
    The selection CSV path: the parent's `dataset.holdout_groups_csv` file by default.

    Fold configs copy the selection under the parent's referenced name, so with
    them on `out` must resolve to that file or the parent's `test` run and the
    CV folds would read different selections. `parent_csv` is None when the
    parent sets no `holdout_groups_csv`.
    """
    parent = parent_csv.resolve() if parent_csv is not None else None
    if write_fold_configs and parent is None:
        raise ValueError("The parent config sets no dataset.holdout_groups_csv.")
    if out is None:
        return parent or config_dir / "holdout_groups.csv"
    path = _resolve(out, REPO_ROOT)
    if write_fold_configs and path != parent:
        raise ValueError(
            f"--out {path} is not the parent's dataset.holdout_groups_csv ({parent}); fold"
            " configs would use a different selection than the parent. Omit --out, or pass"
            " --no-write-fold-configs."
        )
    return path


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument(
        "--config-dir", required=True, help="Config dir, repo-root-relative or absolute."
    )
    parser.add_argument(
        "--beta-sources",
        default=str(DEFAULT_BETA_SOURCES),
        help="CSV with an `id` column of CoralNet sources barred from test (workspace-root default).",
    )
    parser.add_argument("--test-frac", type=float, default=0.10)
    parser.add_argument("--folds", type=int, default=5)
    parser.add_argument("--min-test-points", type=int, default=30)
    parser.add_argument("--max-class-group-loss", type=float, default=0.25)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument(
        "--write-fold-configs",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="Write <config-dir>_fold{k}/ CV configs beside the config dir (default: on).",
    )
    parser.add_argument(
        "--out",
        default=None,
        help="Output CSV. Default: the config's dataset.holdout_groups_csv file.",
    )
    args = parser.parse_args(argv)

    config_dir = _resolve(args.config_dir, REPO_ROOT)
    beta_sources = read_beta_sources(_resolve(args.beta_sources, REPO_ROOT))

    _resolve_local_aws_credentials()

    from mermaid_classifier.pyspacer.dataset import TrainingDataset
    from mermaid_classifier.sagemaker.config import TrainingRunConfig
    from mermaid_classifier.training.holdout_selection import (
        SelectionParams,
        build_coverage_report,
        coverage_warnings,
        select_holdout,
    )

    config = TrainingRunConfig.from_yaml_path(config_dir / CONFIG_FILENAME)
    try:
        out_path = resolve_out_path(
            args.out,
            config_dir,
            config.dataset.holdout_groups_csv_path(config_dir),
            args.write_fold_configs,
        )
    except ValueError as exc:
        raise SystemExit(str(exc)) from exc
    config.apply_env()
    dataset_options, _, _ = config.build_options(config_dir=config_dir)
    # Selection runs on all data: an existing holdout CSV must not tag or drop rows.
    dataset_options = dataclasses.replace(
        dataset_options, holdout_groups_csv=None, holdout_fold="test"
    )

    dataset = TrainingDataset.filtered_annotations_only(dataset_options)
    try:
        rows = dataset.duck_conn.execute(
            "SELECT benthic_attribute_id || '::' || growth_form_id AS class_key,"
            " site, project_id, COUNT(*) AS n"
            " FROM annotations GROUP BY 1, 2, 3"
        ).fetchall()
    finally:
        dataset.cleanup()
    if dataset_options.include_mermaid and not dataset_options.mermaid_project_lookup_uri:
        print(
            "No mermaid_project_lookup_uri in the config: every MERMAID row is project 'all',"
            " so MERMAID holdout is skipped."
        )
        rows = [r for r in rows if r[1] != MERMAID_SITE]
    if not rows:
        raise SystemExit("No annotations to select groups from.")
    counts = pd.DataFrame(
        {
            "class_key": [str(r[0]) for r in rows],
            "site": [str(r[1]) for r in rows],
            "project_id": [str(r[2]) for r in rows],
            "n": [int(r[3]) for r in rows],
        }
    )

    params = SelectionParams(
        test_frac=args.test_frac,
        folds=args.folds,
        min_test_points=args.min_test_points,
        max_class_group_loss=args.max_class_group_loss,
        seed=args.seed,
    )
    coralnet_ids = {
        str(p)
        for site, p in zip(counts["site"], counts["project_id"], strict=True)
        if site == "coralnet"
    }
    print(
        f"{len(beta_sources)} Beta source ids; {len(beta_sources & coralnet_ids)} of them are"
        f" among the {len(coralnet_ids)} CoralNet groups read."
    )
    selection = select_holdout(counts, params, beta_sources)
    write_holdout_csv(out_path, selection.assignments)

    report = build_coverage_report(counts, selection.assignments, params.folds)
    coverage_path = out_path.with_name(out_path.stem + COVERAGE_SUFFIX)
    report.to_csv(coverage_path, index=False)

    print(f"Wrote {len(selection.assignments)} groups to {out_path}")
    print(f"Wrote coverage report to {coverage_path}")
    if args.write_fold_configs:
        for fold_dir in write_fold_configs(config_dir, out_path, params.folds):
            print(f"Wrote fold config {fold_dir}")
    by_fold = pd.Series(selection.assignments).value_counts().sort_index()
    print("Groups per fold:")
    print(by_fold.to_string())
    for warning in [
        *selection.warnings,
        *coverage_warnings(report, params.min_test_points, params.folds),
    ]:
        print(f"WARNING: {warning}")


if __name__ == "__main__":
    main()
